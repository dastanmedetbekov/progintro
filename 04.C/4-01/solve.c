#include <stdio.h>

void p(int *idx, char *text, int res) {
    printf("%c) %s = %d\n", *idx, text, res);
    (*idx)++; 
}

int main() {
    int i = 'a';

    p(&i, "'2' + 3", '2' + 3);
    p(&i, "3 + 'a'", 3 + 'a');
    p(&i, "'z' - 'x'", 'z' - 'x');
    p(&i, "' ' * 10", ' ' * 10);
    p(&i, "'\\n' * 4", '\n' * 4); 
    p(&i, "17 / 5", 17 / 5);
    p(&i, "17 % 5", 17 % 5);
    p(&i, "15 / 17", 15 / 17);
    p(&i, "!25", !25);
    p(&i, "!0", !0);
    p(&i, "23 >> 3", 23 >> 3);
    p(&i, "15 << 3", 15 << 3);
    p(&i, "~35", ~35);
    p(&i, "~(-47)", ~(-47));
    p(&i, "21 ^ 15", 21 ^ 15);
    p(&i, "21 && 10", 21 && 10);
    p(&i, "21 & 10", 21 & 10);
    p(&i, "21 || 7", 21 || 7);
    p(&i, "21 | 7", 21 | 7);
    p(&i, "252 & ~15", 252 & ~15);
    printf("Everything is done!!!\n");



    return 0;
}
